using System.Text;
using System.Text.RegularExpressions;

namespace ghostline
{
    // gateways[].pbx: managed. The PJSIP, dialplan and modem files of a plain Asterisk, from the
    // gateway's modems and the lines that have a phone (lines[].phone). The base pjsip.conf,
    // extensions.conf, quectel.conf and dongle.conf #include them.
    //
    // The dialplan keeps the CDR the way the call journal reads it (Calls.cs MapCdr):
    // - incoming: the call runs on the modem channel and ends on extension <ext>, so channel is
    //   "Quectel/gsm1-…", src the caller and dst the extension;
    // - outgoing: dst is the number as dialed and dstchannel the modem channel;
    // - recordings: <recordings_path>/YYYY/MM/DD/<name>.wav plus -r/-t legs, the name in
    //   CDR(recordingfile). MixMonitor runs on the modem channel for incoming calls and on the
    //   phone channel for outgoing ones, as in FreePBX (Transcriber.LegSpeakers relies on it).
    public static class PbxConfig
    {
        public const string PjsipFile = "pjsip_ghostline.conf";
        public const string DialplanFile = "extensions_ghostline.conf";
        public const string QuectelFile = "quectel_ghostline.conf";
        public const string DongleFile = "dongle_ghostline.conf";
        public static readonly string[] Drivers = { "quectel", "dongle" };

        const string Header = "; Generated by ghostline (settings of the managed gateway). Do not edit: every save rewrites this file.\n";

        // Dial sets: Asterisk pattern -> number given to the modem.
        static readonly (string pattern, string number)[] DialRu =
        {
            ("_+7XXXXXXXXXX", "${EXTEN}"),
            ("_8XXXXXXXXXX", "+7${EXTEN:1}"),
            ("_7XXXXXXXXXX", "+${EXTEN}"),
            ("_9XXXXXXXXX", "+7${EXTEN}"),
            ("_XXX", "${EXTEN}"),                 // short service numbers: 112, 0611
            ("_XXXX", "${EXTEN}"),
        };

        static readonly (string pattern, string number)[] DialIntl =
        {
            ("_+X.", "${EXTEN}"),
            ("_00X.", "+${EXTEN:2}"),
            ("_810X.", "+${EXTEN:3}"),
        };

        public static readonly string[] DialSets = { "ru", "ru+intl" };
        public static readonly string[] Encryptions = { "sdes", "no" };

        static readonly Regex DeviceOk = new(@"^[A-Za-z0-9_-]+$");
        static readonly Regex ExtensionOk = new(@"^[0-9]{2,6}$");
        static readonly Regex SecretOk = new(@"^[A-Za-z0-9]{16,64}$");
        static readonly Regex HostOk = new(@"^[A-Za-z0-9.:-]+$");
        static readonly Regex NetOk = new(@"^[0-9a-fA-F.:]+/[0-9]{1,3}$");
        static readonly Regex PathOk = new(@"^[A-Za-z0-9_./-]+$");
        static readonly Regex PortOk = new(@"^/dev/serial/by-path/[A-Za-z0-9:._-]+$");
        static readonly Regex AlsaOk = new(@"^hw:CARD=[A-Za-z0-9_]+,DEV=[0-9]+$");

        // Known USB modems: the driver and which interfaces carry AT and audio. Only a suggestion for
        // "+ Modem"; the ports are chosen there.
        public record UsbProfile(string Vid, string Pid, string Model, string Driver, int Data, int Audio, bool Uac, bool NoQpcmv);

        public static readonly UsbProfile[] Profiles =
        {
            new("12d1", "140c", "Huawei E1550 (voice firmware)", "dongle", 3, 2, false, false),
            new("12d1", "1001", "Huawei E1550 / E173", "dongle", 2, 1, false, false),
            new("2c7c", "6005", "Quectel EC200A", "quectel", 3, -1, true, true),
            new("2c7c", "0125", "Quectel EC25", "quectel", 2, 1, false, false),
            new("1e0e", "9001", "SIMCom SIM7600", "quectel", 3, 4, false, false),
        };

        public static UsbProfile Profile(string vid, string pid) =>
            Profiles.FirstOrDefault(p => p.Vid == vid?.ToLowerInvariant() && p.Pid == pid?.ToLowerInvariant());

        // A line with a phone, as the generator uses it.
        public record PhoneLine(string Name, string Device, string Tech, LinePhone Phone);

        public static List<PhoneLine> Lines(Settings s) =>
            (s.lines ?? new())
                .Where(ch => !string.IsNullOrWhiteSpace(ch.phone?.extension))
                .Select(ch => new PhoneLine(ch.name, ch.modem, Program.LineFlavor(s, ch)?.Tech, ch.phone))
                .ToList();

        // A line on another gateway (FreePBX during a move) cannot get a phone here.
        public static bool OnManagedAsterisk(Settings s, Channel ch)
        {
            var host = s.ManagedGateway;
            return host != null && ch?.gateway == host.id;
        }

        // Everything that would make a broken or unsafe config; empty: fine to generate.
        public static List<string> Validate(Settings s)
        {
            var errors = new List<string>();
            var gw = s.ManagedGateway;
            if (gw == null)
            {
                errors.Add("no gateway has pbx: managed");
                return errors;
            }
            if (s.gateways.Count(g => g.Managed) > 1) errors.Add("only one gateway can have pbx: managed");
            string at0 = $"gateways[id={gw.id}].managed.";
            var p = gw.managed ?? new ManagedPbx();
            var sip = p.sip ?? new PbxSip();
            if (string.IsNullOrWhiteSpace(p.confDir)) errors.Add(at0 + "conf_dir is empty");
            if (!PathOk.IsMatch(p.asteriskDir ?? "")) errors.Add(at0 + "asterisk_dir: a plain path is expected");
            if (!PathOk.IsMatch(p.recordingsPath ?? "")) errors.Add(at0 + "recordings_path: a plain path is expected");
            if (string.IsNullOrWhiteSpace(sip.tls?.cert) || string.IsNullOrWhiteSpace(sip.tls?.key))
                errors.Add(at0 + "sip.tls.cert and key are needed: phones connect over TLS");
            else if (!PathOk.IsMatch(sip.tls.cert) || !PathOk.IsMatch(sip.tls.key))
                errors.Add(at0 + "sip.tls.cert / key: a plain path is expected");
            if (sip.tls != null && sip.tls.port is < 1 or > 65535) errors.Add(at0 + "sip.tls.port is out of range");
            if (sip.udpPort is < 0 or > 65535) errors.Add(at0 + "sip.udp_port is out of range");
            if (!string.IsNullOrEmpty(sip.externalAddress) && !HostOk.IsMatch(sip.externalAddress))
                errors.Add(at0 + "sip.external_address: a host name or an IP is expected");
            foreach (var net in sip.localNets ?? new())
                if (!NetOk.IsMatch(net)) errors.Add(at0 + $"sip.local_nets: '{net}' is not a network (10.0.0.0/8)");

            var modems = gw.modems ?? new();
            foreach (var m in modems)
            {
                string at = $"modem {m.name}: ";
                if (!DeviceOk.IsMatch(m.name ?? "")) errors.Add(at + "the name: letters, digits, _ and - only");
                if (!Drivers.Contains(m.driver)) errors.Add(at + "driver must be quectel or dongle");
                if (!PortOk.IsMatch(m.data ?? "")) errors.Add(at + "data must be a port under /dev/serial/by-path/");
                if (!string.IsNullOrEmpty(m.audio) && !PortOk.IsMatch(m.audio)) errors.Add(at + "audio must be a port under /dev/serial/by-path/");
                if (!string.IsNullOrEmpty(m.alsadev) && !AlsaOk.IsMatch(m.alsadev)) errors.Add(at + "alsadev must look like hw:CARD=Android,DEV=0");
                if (m.driver == "dongle" && (string.IsNullOrEmpty(m.audio) || !string.IsNullOrEmpty(m.alsadev) || m.noqpcmv))
                    errors.Add(at + "a dongle needs an audio port (no sound card, no noqpcmv)");
                if (m.driver == "quectel" && string.IsNullOrEmpty(m.audio) == string.IsNullOrEmpty(m.alsadev))
                    errors.Add(at + "either an audio port or a sound card (alsadev)");
                if (m.audio != null && m.audio == m.data) errors.Add(at + "data and audio are the same port");
            }
            foreach (var g in modems.GroupBy(m => m.name).Where(g => g.Count() > 1))
                errors.Add($"modem {g.Key} is listed more than once");
            foreach (var g in modems.SelectMany(m => new[] { m.data, m.audio, m.alsadev }).Where(x => !string.IsNullOrEmpty(x))
                         .GroupBy(x => x).Where(g => g.Count() > 1))
                errors.Add($"{g.Key} is used by more than one modem");

            var lines = Lines(s);
            if (lines.Count == 0 && modems.Count == 0) errors.Add("no modem and no line with a phone");
            foreach (var l in lines)
            {
                string at = $"line {l.Name}: ";
                if (!OnManagedAsterisk(s, s.lines.First(c => c.name == l.Name)))
                    errors.Add(at + "its modem is on another PBX (a phone needs the gateway with pbx: managed)");
                else if (l.Tech == null) errors.Add(at + $"gateway {gw.id} has no modem '{l.Device}'");
                if (!DeviceOk.IsMatch(l.Device ?? "")) errors.Add(at + "the modem name is empty or has odd characters");
                if (!ExtensionOk.IsMatch(l.Phone.extension)) errors.Add(at + "phone.extension must be 2-6 digits");
                if (!SecretOk.IsMatch(l.Phone.secret ?? "")) errors.Add(at + "no phone secret yet (generate it in the line's phone settings)");
                // Empty: the default (ru, sdes).
                if (!string.IsNullOrEmpty(l.Phone.dial) && !DialSets.Contains(l.Phone.dial))
                    errors.Add(at + "phone.dial must be one of: " + string.Join(", ", DialSets));
                if (!string.IsNullOrEmpty(l.Phone.encryption) && !Encryptions.Contains(l.Phone.encryption))
                    errors.Add(at + "phone.encryption must be sdes or no");
            }
            foreach (var g in lines.GroupBy(l => l.Phone.extension).Where(g => g.Count() > 1))
                errors.Add($"extension {g.Key} is used by more than one line");
            foreach (var g in lines.GroupBy(l => l.Device).Where(g => g.Count() > 1))
                errors.Add($"device {g.Key} has more than one phone");
            return errors;
        }

        // File name -> text. Call Validate first.
        public static SortedDictionary<string, string> Generate(Settings s)
        {
            var gw = s.ManagedGateway;
            return new(StringComparer.Ordinal)
            {
                [PjsipFile] = Pjsip(s, gw.managed),
                [DialplanFile] = Dialplan(s, gw),
                [QuectelFile] = ModemFile(gw, "quectel"),
                [DongleFile] = ModemFile(gw, "dongle"),
            };
        }

        // Device sections; quectel.conf / dongle.conf keep [general] (and [defaults]) and #include this.
        static string ModemFile(Gateway gw, string driver)
        {
            var sb = new StringBuilder(Header);
            foreach (var m in (gw.modems ?? new()).Where(m => m.driver == driver))
            {
                sb.Append($"\n[{m.name}]\n");
                if (!string.IsNullOrEmpty(m.audio)) sb.Append($"audio={m.audio}\n");
                sb.Append($"data={m.data}\n");
                if (!string.IsNullOrEmpty(m.alsadev)) sb.Append("quec_uac=1\n").Append($"alsadev={m.alsadev}\n");
                if (m.noqpcmv) sb.Append("noqpcmv=1\n");
                sb.Append($"context=gl-in-{m.name}\n");
                if (driver == "quectel") sb.Append("resetquectel=yes\ninitstate=start\nautodeletesms=yes\n");
            }
            return sb.ToString();
        }

        // A relative certificate path is inside conf_dir, which Asterisk sees as asterisk_dir.
        static string AsteriskPath(ManagedPbx p, string path) =>
            path.StartsWith("/") ? path : p.asteriskDir.TrimEnd('/') + "/" + path;

        static string Pjsip(Settings s, ManagedPbx m)
        {
            var p = m.sip;
            var sb = new StringBuilder(Header);
            void Nat()
            {
                if (!string.IsNullOrEmpty(p.externalAddress))
                {
                    sb.Append("external_media_address=").Append(p.externalAddress).Append('\n');
                    sb.Append("external_signaling_address=").Append(p.externalAddress).Append('\n');
                }
                foreach (var net in p.localNets ?? new())
                    sb.Append("local_net=").Append(net).Append('\n');
            }

            sb.Append("\n[gl-tls]\ntype=transport\nprotocol=tls\n");
            sb.Append("bind=0.0.0.0:").Append(p.tls.port).Append('\n');
            sb.Append("cert_file=").Append(AsteriskPath(m, p.tls.cert)).Append('\n');
            sb.Append("priv_key_file=").Append(AsteriskPath(m, p.tls.key)).Append('\n');
            sb.Append("method=tlsv1_2\n");
            Nat();
            if (p.udpPort > 0)
            {
                sb.Append("\n[gl-udp]\ntype=transport\nprotocol=udp\n");
                sb.Append("bind=0.0.0.0:").Append(p.udpPort).Append('\n');
                Nat();
            }

            foreach (var l in Lines(s))
            {
                string ext = l.Phone.extension;
                sb.Append($"\n; line {l.Name}: SIM {l.Device}\n");
                sb.Append($"[{ext}]\ntype=endpoint\ncontext=gl-out-{l.Device}\n");
                sb.Append("disallow=all\nallow=alaw,ulaw\n");
                sb.Append($"auth={ext}\naors={ext}\n");
                sb.Append($"callerid=\"{l.Name}\" <{ext}>\n");
                sb.Append("media_encryption=").Append(l.Phone.encryption == "no" ? "no" : "sdes").Append('\n');
                sb.Append("direct_media=no\nrtp_symmetric=yes\nforce_rport=yes\nrewrite_contact=yes\n");
                sb.Append("dtmf_mode=rfc4733\ntrust_id_inbound=no\nsend_pai=no\nallow_subscribe=no\n");
                sb.Append($"\n[{ext}]\ntype=auth\nauth_type=userpass\nusername={ext}\npassword={l.Phone.secret}\n");
                sb.Append($"\n[{ext}]\ntype=aor\nmax_contacts=1\nremove_existing=yes\nqualify_frequency=60\n");
            }
            return sb.ToString();
        }

        static string Dialplan(Settings s, Gateway gw)
        {
            var lines = Lines(s);
            string rec = gw.managed.recordingsPath.TrimEnd('/');
            var sb = new StringBuilder(Header);

            // Records the call on the current channel. ARG1: the file name prefix ("in-11", "out-0611").
            sb.Append("\n[gl-record]\n");
            sb.Append("exten => s,1,Set(GL_DIR=").Append(rec).Append("/${STRFTIME(${EPOCH},,%Y/%m/%d)})\n");
            sb.Append(" same => n,Set(GL_FILE=${ARG1}-${FILTER(+0123456789,${CALLERID(num)})}-${STRFTIME(${EPOCH},,%Y%m%d-%H%M%S)}-${UNIQUEID})\n");
            sb.Append(" same => n,Set(CDR(recordingfile)=${GL_FILE}.wav)\n");
            sb.Append(" same => n,MixMonitor(${GL_DIR}/${GL_FILE}.wav,r(${GL_DIR}/${GL_FILE}-r.wav)t(${GL_DIR}/${GL_FILE}-t.wav))\n");
            sb.Append(" same => n,Return()\n");

            // A modem without a phone: SMS and USSD as usual, calls are not answered.
            foreach (var m in (gw.modems ?? new()).Where(m => lines.All(l => l.Device != m.name)))
            {
                sb.Append($"\n; modem {m.name}: no phone, calls are not answered\n");
                sb.Append($"[gl-in-{m.name}]\n");
                sb.Append("exten => sms,1,Hangup()\n");
                sb.Append("exten => ussd,1,Hangup()\n");
                sb.Append("exten => s,1,Hangup()\n");
                sb.Append("exten => _X.,1,Hangup()\n");
                sb.Append("exten => _+X.,1,Hangup()\n");
            }

            foreach (var l in lines)
            {
                string ext = l.Phone.extension, dev = l.Device;

                // The modem delivers calls to "s" (or to its own number) and SMS/USSD to service extensions
                // that ghostline handles over AMI. The jump to the extension makes it the CDR dst.
                sb.Append($"\n; line {l.Name}: SIM {dev} rings phone {ext}\n");
                sb.Append($"[gl-in-{dev}]\n");
                sb.Append("exten => sms,1,Hangup()\n");
                sb.Append("exten => ussd,1,Hangup()\n");
                sb.Append($"exten => s,1,Goto(gl-ring-{dev},{ext},1)\n");
                sb.Append($"exten => _X.,1,Goto(gl-ring-{dev},{ext},1)\n");
                sb.Append($"exten => _+X.,1,Goto(gl-ring-{dev},{ext},1)\n");

                sb.Append($"\n[gl-ring-{dev}]\n");
                sb.Append($"exten => {ext},1,Set(CALLERID(name)=${{CALLERID(num)}})\n");
                sb.Append($" same => n,Gosub(gl-record,s,1(in-{ext}))\n");
                sb.Append($" same => n,Dial(PJSIP/{ext},60)\n");
                sb.Append(" same => n,Hangup()\n");

                // Phone -> the other phones by extension (not recorded), the rest out through the SIM.
                // The other phones are listed here rather than included: an included context is searched
                // after the patterns, and _XXX would take a 3-digit extension.
                sb.Append($"\n; phone {ext} calls out through SIM {dev}\n");
                sb.Append($"[gl-out-{dev}]\n");
                foreach (var other in lines.Where(o => o != l))
                    sb.Append($"exten => {other.Phone.extension},1,Dial(PJSIP/{other.Phone.extension},60)\n same => n,Hangup()\n");
                var set = l.Phone.dial == "ru+intl" ? DialRu.Concat(DialIntl) : DialRu;
                foreach (var (pattern, number) in set)
                    sb.Append($"exten => {pattern},1,Set(GL_NUM={number})\n same => n,Goto(gl-call-{dev},${{EXTEN}},1)\n");

                // Goto keeps the dialed number as the extension, so it stays the CDR dst.
                sb.Append($"\n[gl-call-{dev}]\n");
                sb.Append("exten => _[+0-9].,1,Gosub(gl-record,s,1(out-${EXTEN}))\n");
                sb.Append($" same => n,Dial({l.Tech}/{dev}/${{GL_NUM}},120)\n");
                sb.Append(" same => n,Hangup()\n");
            }
            return sb.ToString();
        }

        // A new phone secret: 24 letters and digits (no characters that need quoting in pjsip.conf).
        public static string NewSecret()
        {
            const string chars = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789";
            var bytes = System.Security.Cryptography.RandomNumberGenerator.GetBytes(24);
            return new string(bytes.Select(b => chars[b % chars.Length]).ToArray());
        }
    }
